export function translateText(value: string, language: AppLanguage) {
  if (language !== "en") return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const trimmed = value.trim();
  if (englishTranslations[trimmed]) return `${leading}${englishTranslations[trimmed]}${trailing}`;

  const patterned = trimmed
    .replace(/^غلاف\s+/, "Cover of ")
    .replace(/^من\s+/, "From ")
    .replace(/^المالك\s+/, "Owner ")
    .replace(/^الكتاب:\s*/, "Book: ")
    .replace(/^الكاتب:\s*/, "Author: ")
    .replace(/^اقتنيت:\s*/, "You received: ")
    .replace(/^تم بيع:\s*/, "You gave away: ")
    .replace(/^شراء بالنقاط\s*·\s*(\d+)\s*نقطة$/, "Points purchase · $1 points")
    .replace(/^(\d+)\s+نقاط$/, "$1 points")
    .replace(/^(\d+)\s+نقطة$/, "$1 point")
    .replace(/^تم إرسال طلبك وحجز الكتاب المطلوب مؤقتاً\.?$/, "Your request was sent and the requested book is temporarily reserved.");
  if (patterned !== trimmed) return `${leading}${patterned}${trailing}`;
  return value;
}
